def instructions(decision):
    key=decision['entity_id'].rsplit('.',1)[-1]
    if key=='dualcast' and '.upgrade.' in decision['field_path']:
        return (['升级版双重释放是否为0费，且仍然激发同一个充能球两次？'],
                '这句原文用文字概括升级效果，需要同时核对费用和激发次数。',
                '并排查看基础版和升级版卡面，记录费用和描述。')
    return PROMPTS[key]


